"""
tools/fetch_datasets.py -- build extra evaluation collections in the
repo's own format, so parameters can be validated on more than one
collection shape. NOT part of the submission.

Why this exists
---------------
The graded collection is announced in the spec, so the primary tuning
signal is that collection's released dev topics. But there are only ~50 of
those, the held-out topics are different ones, and a parameter setting
chosen to squeeze the last 0.005 nDCG out of 50 topics is very likely
fitting those topics rather than the collection. Checking a setting on
two or three collections of genuinely different shape (document length,
vocabulary, query style) is the cheap guard against that -- the same
reasoning behind the avgdl/N regimes in your Assignment 1 `adapt_params`.

The catch, and why it is actually useful
----------------------------------------
Only the graded collection has a staff-released candidates file. For every
other collection this script has to synthesise the candidate pool with its
own first-pass retriever (BM25 below). That is not a workaround, it is the
more informative test: `docs/GRADING.md` says the reference retriever is
undisclosed precisely so nobody builds around one score distribution. A
parameter setting that survives *your* BM25 pool, a deliberately weakened
pool (`--degrade`), and the staff pool is a setting that is not depending
on any of them.

Usage
-----
    # a small BEIR collection (needs network; ir_datasets downloads it)
    python -m tools.fetch_datasets --dataset beir/nfcorpus --out data/nfcorpus

    # candidates for a collection you already have on disk
    python -m tools.fetch_datasets --from-local data/full --k1 0.9 --b 0.4

    # a deliberately weaker first pass, to test candidate-quality robustness
    python -m tools.fetch_datasets --from-local data/full --degrade 0.3 \
        --out-candidates data/full/candidates_weak.jsonl

Suggested collections to validate on, chosen for shape spread:
    beir/nfcorpus   ~3.6k docs, short medical abstracts, long queries
    beir/scifact    ~5.2k docs, scientific claims as queries
    beir/fiqa       ~57k docs, forum answers, mid-length
    beir/trec-covid ~171k docs, abstracts (the download script's default)
"""
import argparse
import json
import math
import os
import random
import re
from collections import Counter, defaultdict
from typing import Dict, List, Tuple

_TOKEN_RE = re.compile(r"[a-z0-9]+")
TOP_K = 100


def _tok(text: str) -> List[str]:
    return [t for t in _TOKEN_RE.findall(text.lower()) if len(t) > 1]


class BM25:
    """Small in-memory BM25 first pass. Independent of submission/feedback.py
    on purpose -- a candidate pool generated by the same model that later
    reranks it would flatter the reranker."""

    def __init__(self, k1: float = 0.9, b: float = 0.4) -> None:
        self.k1, self.b = k1, b
        self.postings: Dict[str, List[Tuple[int, int]]] = defaultdict(list)
        self.doc_ids: List[str] = []
        self.dl: List[int] = []
        self.avgdl = 0.0

    def index(self, docs) -> None:
        for doc_id, text in docs:
            idx = len(self.doc_ids)
            self.doc_ids.append(doc_id)
            counts = Counter(_tok(text))
            self.dl.append(sum(counts.values()))
            for term, tf in counts.items():
                self.postings[term].append((idx, tf))
        n = len(self.doc_ids)
        self.avgdl = (sum(self.dl) / n) if n else 0.0

    def search(self, query: str, k: int = TOP_K) -> List[Tuple[str, float]]:
        n = len(self.doc_ids)
        scores: Dict[int, float] = defaultdict(float)
        for term in _tok(query):
            plist = self.postings.get(term)
            if not plist:
                continue
            idf = math.log(1.0 + (n - len(plist) + 0.5) / (len(plist) + 0.5))
            for idx, tf in plist:
                norm = 1.0 - self.b + self.b * (self.dl[idx] / self.avgdl if self.avgdl else 1.0)
                scores[idx] += idf * (tf * (self.k1 + 1.0)) / (tf + self.k1 * norm)
        top = sorted(scores.items(), key=lambda kv: (-kv[1], self.doc_ids[kv[0]]))[:k]
        return [(self.doc_ids[i], s) for i, s in top]


def write_candidates(path, queries, bm25, degrade: float, seed: int) -> None:
    """Top-100 per query, optionally degraded.

    `degrade` replaces that fraction of the pool with random documents,
    simulating a weaker reference retriever. Recall drops and the pool's
    ordering carries less signal -- which is exactly the condition under
    which an over-tuned reranker falls apart.
    """
    rng = random.Random(seed)
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        for qid, text in queries:
            ranked = bm25.search(text, TOP_K)
            if degrade > 0 and ranked:
                keep = max(1, int(round(len(ranked) * (1.0 - degrade))))
                kept = ranked[:keep]
                have = {d for d, _ in kept}
                pool = [d for d in bm25.doc_ids if d not in have]
                extra = rng.sample(pool, min(len(ranked) - keep, len(pool)))
                kept += [(d, 0.0) for d in extra]
                ranked = kept
            fh.write(json.dumps({"qid": qid, "candidates": [[d, s] for d, s in ranked]}) + "\n")


def load_local(path: str):
    docs, queries, qrels_lines = [], [], []
    with open(os.path.join(path, "corpus.jsonl"), encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                obj = json.loads(line)
                docs.append((obj["doc_id"], obj.get("text", "")))
    with open(os.path.join(path, "queries_dev.tsv"), encoding="utf-8") as fh:
        for line in fh:
            parts = line.rstrip("\n").split("\t")
            if len(parts) >= 2:
                queries.append((parts[0], parts[1]))
    return docs, queries, qrels_lines


def fetch_ir_datasets(dataset: str, out: str):
    import ir_datasets

    ds = ir_datasets.load(dataset)
    os.makedirs(out, exist_ok=True)

    docs = []
    with open(os.path.join(out, "corpus.jsonl"), "w", encoding="utf-8") as fh:
        for doc in ds.docs_iter():
            text = doc.default_text() if hasattr(doc, "default_text") else getattr(doc, "text", "")
            fh.write(json.dumps({"doc_id": doc.doc_id, "text": text}) + "\n")
            docs.append((doc.doc_id, text))

    queries = []
    with open(os.path.join(out, "queries_dev.tsv"), "w", encoding="utf-8") as fh:
        for q in ds.queries_iter():
            text = q.default_text() if hasattr(q, "default_text") else getattr(q, "text", "")
            text = " ".join(text.split())
            fh.write(f"{q.query_id}\t{text}\n")
            queries.append((q.query_id, text))

    with open(os.path.join(out, "qrels_dev.txt"), "w", encoding="utf-8") as fh:
        for qrel in ds.qrels_iter():
            fh.write(f"{qrel.query_id} 0 {qrel.doc_id} {qrel.relevance}\n")

    print(f"{dataset}: {len(docs)} docs, {len(queries)} queries -> {out}")
    return docs, queries


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dataset", default=None, help="ir_datasets id, e.g. beir/nfcorpus")
    ap.add_argument("--from-local", default=None, help="directory already in repo format")
    ap.add_argument("--out", default=None)
    ap.add_argument("--out-candidates", default=None)
    ap.add_argument("--k1", type=float, default=0.9)
    ap.add_argument("--b", type=float, default=0.4)
    ap.add_argument("--degrade", type=float, default=0.0,
                    help="fraction of the pool to replace with random docs")
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()

    if args.dataset:
        out = args.out or os.path.join("data", args.dataset.split("/")[-1])
        docs, queries = fetch_ir_datasets(args.dataset, out)
    elif args.from_local:
        out = args.out or args.from_local
        docs, queries, _ = load_local(args.from_local)
        print(f"{args.from_local}: {len(docs)} docs, {len(queries)} queries")
    else:
        raise SystemExit("pass --dataset or --from-local")

    bm25 = BM25(k1=args.k1, b=args.b)
    bm25.index(docs)
    suffix = "_weak" if args.degrade > 0 else ""
    cand_path = args.out_candidates or os.path.join(out, f"candidates_dev{suffix}.jsonl")
    write_candidates(cand_path, queries, bm25, args.degrade, args.seed)
    print(f"candidates (k1={args.k1}, b={args.b}, degrade={args.degrade}) -> {cand_path}")


if __name__ == "__main__":
    main()
